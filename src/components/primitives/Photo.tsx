import type { CSSProperties } from 'react'
import { cx } from '@/lib/cx'

/**
 * Photo.
 *
 * The first raster imagery on this site, and it arrives into a visual system
 * that was built without any — flat planes, hairlines and type, no shadows, one
 * saturated surface. So the job here is not "render an image", it is "render an
 * image without breaking the three rules the rest of the page is holding to".
 *
 * WHAT THIS DOES NOT DO, and each omission is a decision:
 *
 *   - NO ROUNDED CORNERS. `--radius-panel` is for things that open and
 *     `--radius-action` for things you press. A photograph is neither; it is
 *     structure, and structure on this site is square.
 *   - NO SHADOW. There are zero box-shadows on the site and a photo is not the
 *     place to introduce the first one. Separation is a hairline, the same as
 *     everything else.
 *   - NO FILTER, NO DUOTONE, NO ACCENT WASH. Tinting client photography into
 *     the palette is the same class of mistake as repainting the mascot's
 *     artwork: it takes something authored and quietly makes it ours. If a
 *     photo clashes, the fix is placement and scale.
 *
 * WHAT IT DOES DO:
 *
 *   - `<picture>` with AVIF, then WebP, then JPEG. Sources are generated by
 *     `tools/photos.mjs` at 640 / 1280 / 1920 and committed, so the build never
 *     depends on anyone's CDN.
 *   - Intrinsic `width`/`height` on the `<img>`, always. Without them the page
 *     reflows as each photo arrives, and a layout that jumps is a worse defect
 *     than a heavy image.
 *   - `sizes` is REQUIRED rather than defaulted. A wrong `sizes` silently makes
 *     the whole srcset pointless — the browser picks against a lie — and a
 *     default of `100vw` would be wrong for every use on this page, all of
 *     which are columns. Making it required means the caller has to look.
 */

const WIDTHS = [640, 1280, 1920] as const

export type PhotoProps = {
  /** Basename from `tools/photos.mjs`, e.g. `careers-9`. */
  file: string
  alt: string
  /** Intrinsic dimensions of the source, for the aspect ratio the box reserves. */
  width: number
  height: number
  /**
   * The rendered width at each breakpoint, e.g.
   * `(min-width: 1024px) 42vw, 100vw`. No default — see the note above.
   */
  sizes: string
  /**
   * `eager` only for a photo above the fold. Everything on this page is below
   * it, so the default is right and the prop exists for the one day it is not.
   */
  loading?: 'lazy' | 'eager'
  /**
   * Which ramp the frame is drawn from.
   *
   * A PROP RATHER THAN A CLASS OVERRIDE, because the frame is a Tailwind
   * utility and so is anything a caller would pass to beat it — same
   * specificity, so which one wins is decided by their order in the generated
   * stylesheet, not by the call site. That is a coin flip, and it would land on
   * a paper hairline against the forest band roughly whenever the build
   * reordered. Stating the ramp is the only version of this that is stable.
   */
  tone?: 'paper' | 'inverse'
  /**
   * `false` drops the hairline frame and the placeholder ground.
   *
   * For collage only — images butted edge to edge, where the frame would draw a
   * grid over what is supposed to read as one continuous band. A framed photo is
   * an object on the page; an unframed one is the page. Do not reach for this to
   * make a single image look cleaner: the frame is what stops a loading image
   * from being a hole rather than a deliberate gap.
   */
  frame?: boolean
  className?: string
  style?: CSSProperties
}

export function Photo({
  file,
  alt,
  width,
  height,
  sizes,
  loading = 'lazy',
  tone = 'paper',
  frame = true,
  className,
  style,
}: PhotoProps) {
  const set = (ext: string) =>
    WIDTHS.map((w) => `/photos/${file}-${w}.${ext} ${w}w`).join(', ')

  return (
    // The frame is the hairline, and it sits on the wrapper rather than the
    // <img> so it survives while the image is still loading — an empty box with
    // a rule around it is a deliberate-looking gap; an unframed empty box is a
    // hole in the page.
    // `overflow-clip`, NOT `overflow-hidden`, and the difference is not
    // cosmetic. `hidden` creates a scroll container; a `view()` timeline on
    // anything INSIDE a scroll container that never scrolls resolves against a
    // box that never moves and sits frozen at 0% forever. `clip` clips
    // identically and creates no scrollport. That is what lets a
    // photograph animate inside its own frame (`data-scroll="photo-pan"`), and
    // it is the same trap the hero and the contact band already avoid — see the
    // note above the continuous-motion block in index.css.
    <figure
      className={cx(
        'm-0 overflow-clip',
        frame &&
          (tone === 'inverse'
            ? 'border border-inverse-hairline-strong bg-inverse-overlay'
            : 'border border-hairline bg-surface'),
        className,
      )}
      style={style}
    >
      <picture>
        <source type="image/avif" srcSet={set('avif')} sizes={sizes} />
        <source type="image/webp" srcSet={set('webp')} sizes={sizes} />
        <img
          src={`/photos/${file}-1280.jpg`}
          srcSet={set('jpg')}
          sizes={sizes}
          alt={alt}
          width={width}
          height={height}
          loading={loading}
          decoding="async"
          // `block` kills the inline-baseline gap under the image, which would
          // otherwise show as a few pixels of surface inside the frame.
          className="block h-full w-full object-cover"
        />
      </picture>
    </figure>
  )
}
